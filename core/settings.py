# Formats Django will try to parse when a user types time into a form.
# Order matters — first match wins. Keep 12-hour variants first so a user
# typing "02:30 PM" works, and keep 24-hour variants as a fallback.
# NOTE: bare "%I:%M" (no AM/PM) was removed — it parsed "02:30" as AM
# silently, corrupting afternoon entries typed without a marker.
